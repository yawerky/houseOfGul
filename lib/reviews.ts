// Occasions and recipients for template filling
const occasions = ['birthday', 'anniversary', 'wedding', "mother's day", "valentine's day", 'housewarming', 'promotion celebration', 'new baby celebration']
const recipients = ['wife', 'mother', 'sister', 'friend', 'girlfriend', 'daughter', 'aunt', 'grandmother', 'colleague', 'boss']

// Generate a random date within last 6 months
function generateRandomDate(): Date {
  const now = new Date()
  const sixMonthsAgo = new Date(now.getTime() - 180 * 24 * 60 * 60 * 1000)
  const randomTime = sixMonthsAgo.getTime() + Math.random() * (now.getTime() - sixMonthsAgo.getTime())
  return new Date(randomTime)
}

// Format date as "X days/weeks/months ago"
export function formatReviewDate(date: Date): string {
  const now = new Date()
  const diffMs = now.getTime() - date.getTime()
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24))

  if (diffDays === 0) return 'Today'
  if (diffDays === 1) return 'Yesterday'
  if (diffDays < 7) return `${diffDays} days ago`
  if (diffDays < 30) return `${Math.floor(diffDays / 7)} week${Math.floor(diffDays / 7) > 1 ? 's' : ''} ago`
  if (diffDays < 60) return '1 month ago'
  return `${Math.floor(diffDays / 30)} months ago`
}

// Fill template with random values
function fillTemplate(template: string): string {
  const occasion = occasions[Math.floor(Math.random() * occasions.length)]
  const recipient = recipients[Math.floor(Math.random() * recipients.length)]
  return template.replace('{occasion}', occasion).replace('{recipient}', recipient)
}

