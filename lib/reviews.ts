// Generate deterministic reviews based on product slug
export function generateReviews(productSlug: string, count: number = 50): Review[] {
  const reviews: Review[] = []

  // Seed random based on product slug for consistency
  let seed = 0
  for (let i = 0; i < productSlug.length; i++) {
    seed += productSlug.charCodeAt(i)
  }

  // Simple seeded random function
  const seededRandom = () => {
    seed = (seed * 9301 + 49297) % 233280
    return seed / 233280
  }

  // Rating distribution: 60% 5-star, 25% 4-star, 10% 3-star, 5% 2-star or below
  const ratingDistribution = [
    ...Array(30).fill(5),
    ...Array(12).fill(4),
    ...Array(5).fill(3),
    ...Array(2).fill(2),
    ...Array(1).fill(1),
  ]

  for (let i = 0; i < count; i++) {
    const rating = ratingDistribution[Math.floor(seededRandom() * ratingDistribution.length)]
    const firstName = firstNames[Math.floor(seededRandom() * firstNames.length)]
    const lastInitial = lastInitials[Math.floor(seededRandom() * lastInitials.length)]
    const locality = jaipurLocalities[Math.floor(seededRandom() * jaipurLocalities.length)]

    let templates: string[]
    if (rating === 5) templates = fiveStarTemplates
    else if (rating === 4) templates = fourStarTemplates
    else templates = threeStarTemplates

    const template = templates[Math.floor(seededRandom() * templates.length)]
    const content = fillTemplate(template)

    // Generate title from content
    const words = content.split(' ').slice(0, 4).join(' ')
    const title = words.length > 30 ? words.substring(0, 30) + '...' : words

    const date = generateRandomDate()
    date.setTime(date.getTime() - i * 24 * 60 * 60 * 1000 * seededRandom() * 3) // Spread dates

    const review: Review = {
      id: `review-${productSlug}-${i}`,
      name: `${firstName} ${lastInitial}.`,
      location: locality,
      rating,
      title,
      content,
      date,
      dateFormatted: formatReviewDate(date),
      verified: seededRandom() > 0.2, // 80% verified
      helpful: Math.floor(seededRandom() * 50),
    }

    // Add images to ~20% of reviews
    if (seededRandom() > 0.8) {
      const numImages = Math.floor(seededRandom() * 3) + 1
      review.images = []
      for (let j = 0; j < numImages; j++) {
        review.images.push(reviewImages[Math.floor(seededRandom() * reviewImages.length)])
      }
    }

    // Add video to ~5% of reviews
    if (seededRandom() > 0.95) {
      review.video = reviewVideos[Math.floor(seededRandom() * reviewVideos.length)]
    }

    // Add seller reply to ~15% of reviews
    if (seededRandom() > 0.85) {
      review.reply = {
        content: "Thank you for your valuable feedback! We're glad you loved our flowers. Looking forward to serving you again.",
        date: formatReviewDate(new Date(date.getTime() + 24 * 60 * 60 * 1000))
      }
    }

    reviews.push(review)
  }

  // Sort by date (newest first)
  reviews.sort((a, b) => b.date.getTime() - a.date.getTime())

  return reviews
}

// Calculate rating summary
export interface RatingSummary {
  average: number
  total: number
  distribution: { stars: number; count: number; percentage: number }[]
}

export function calculateRatingSummary(reviews: Review[]): RatingSummary {
  const total = reviews.length
  const sum = reviews.reduce((acc, r) => acc + r.rating, 0)
  const average = total > 0 ? sum / total : 0

  const distribution = [5, 4, 3, 2, 1].map(stars => {
    const count = reviews.filter(r => r.rating === stars).length
    return {
      stars,
      count,
      percentage: total > 0 ? (count / total) * 100 : 0
    }
  })

  return { average: Math.round(average * 10) / 10, total, distribution }
}

